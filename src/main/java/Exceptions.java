/**
 * Represents a custom exception for the Rainbow application.
 * This exception can be used to handle application-specific error conditions.
 */
public class Exceptions extends Exception {
    /**
     * Creates a new Exceptions object with the specified error message.
     *
     * @param message The detail message explaining the exception.
     */
    public Exceptions(String message) {
        super(message);
    }


}